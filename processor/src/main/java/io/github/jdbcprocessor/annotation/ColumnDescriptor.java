package io.github.jdbcprocessor.annotation;

/**
 * Immutable descriptor of a SQL column bound to an entity field.
 *
 * <p>Used by {@link io.github.jdbcprocessor.mapper.EntityMapper#columns()} so that
 * the generated repository implementation can build its SQL statements (INSERT,
 * UPDATE, SELECT) without any runtime reflection.</p>
 *
 * @param fieldName   Java field name in the entity (e.g. {@code "firstName"})
 * @param columnName  corresponding SQL column name (e.g. {@code "first_name"})
 * @param id          {@code true} if this column is the primary key
 * @param generated   {@code true} if the value is auto-generated by the database
 *                    (e.g. {@code AUTO_INCREMENT}); the column is then excluded
 *                    from INSERT statements
 */
public record ColumnDescriptor(
        String fieldName,
        String columnName,
        boolean id,
        boolean generated) {

    /** Shortcut: plain column (neither PK nor auto-generated). */
    public static ColumnDescriptor of(String fieldName, String columnName) {
        return new ColumnDescriptor(fieldName, columnName, false, false);
    }

    /** Shortcut: auto-generated primary key column. */
    public static ColumnDescriptor id(String fieldName, String columnName) {
        return new ColumnDescriptor(fieldName, columnName, true, true);
    }

    /** Shortcut: manually supplied primary key (not auto-generated). */
    public static ColumnDescriptor idManual(String fieldName, String columnName) {
        return new ColumnDescriptor(fieldName, columnName, true, false);
    }
}
