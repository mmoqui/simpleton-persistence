  /** Converts a field name to a VarHandle constant name: {@code "firstName"} → {@code "VH_FIRST_NAME"}. */
  private static String varHandleName(String fieldName) {
    return "VH_" + fieldName.replaceAll("([a-z])([A-Z])", "$1_$2").toUpperCase();
  }

  /**
   * Resolves a fully-qualified or primitive type name to the appropriate
   * JavaPoet {@link TypeName}.
   *
   * <p>{@link ClassName#bestGuess} only handles reference types and throws
   * when given a primitive name such as {@code "int"} or {@code "long"}.
   * This helper maps the eight Java primitives to their {@link TypeName}
   * constants and delegates everything else to {@code ClassName.bestGuess}.</p>
   *
   * @param fqn the type name as returned by the mirror API's {@code toString()}
   *            (e.g. {@code "int"}, {@code "java.lang.String"}, {@code "io.example.User"})
   * @return the corresponding {@link TypeName}
   */
  private static TypeName typeNameOf(String fqn) {
    return switch (fqn) {
      case "boolean" -> TypeName.BOOLEAN;
      case "byte"    -> TypeName.BYTE;
      case "short"   -> TypeName.SHORT;
      case "int"     -> TypeName.INT;
      case "long"    -> TypeName.LONG;
      case "char"    -> TypeName.CHAR;
      case "float"   -> TypeName.FLOAT;
      case "double"  -> TypeName.DOUBLE;
      default        -> ClassName.bestGuess(fqn);
    };
  }

  private static String simpleName(String fqn) {
    return fqn.contains(".") ? fqn.substring(fqn.lastIndexOf('.') + 1) : fqn;
  }
