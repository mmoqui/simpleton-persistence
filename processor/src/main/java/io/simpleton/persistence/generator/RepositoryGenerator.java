  private TypeSpec buildFactory(String factoryName, String implName,
                                String ifaceFqn, String packageName,
                                EntityMetadata meta) {
    ClassName entityCls  = ClassName.bestGuess(meta.getEntityFqn());
    ClassName ifaceCls   = ClassName.bestGuess(ifaceFqn);
    ClassName implCls    = ClassName.get(packageName, implName);
    ParameterizedTypeName mapperType = ParameterizedTypeName.get(
        ClassName.get(EntityMapper.class), entityCls);
    ParameterizedTypeName factoryIface = ParameterizedTypeName.get(
        ClassName.get(RepositoryFactory.class), ifaceCls);

    MethodSpec createMeth = MethodSpec.methodBuilder("create")
        .addModifiers(Modifier.PUBLIC).addAnnotation(Override.class)
        .returns(ifaceCls)
        .addStatement("return new $T(dataSource, mapper)", implCls)
        .build();

    TypeSpec.Builder fb = TypeSpec.classBuilder(factoryName)
        .addModifiers(Modifier.PUBLIC, Modifier.FINAL)
        .addSuperinterface(factoryIface)
        .addField(javax.sql.DataSource.class, "dataSource", Modifier.PRIVATE, Modifier.FINAL)
        .addField(mapperType,                 "mapper",     Modifier.PRIVATE, Modifier.FINAL);

    if (meta.hasCustomMapper()) {
      ClassName customMapper = ClassName.bestGuess(meta.getCustomMapperFqn());
      fb.addMethod(MethodSpec.constructorBuilder()
          .addModifiers(Modifier.PUBLIC)
          .addParameter(javax.sql.DataSource.class, "dataSource")
          .addStatement("this.dataSource = dataSource")
          .addStatement("this.mapper = new $T()", customMapper)
          .build());
    } else {
      fb.addType(buildDefaultMapper(entityCls, mapperType, meta));
      fb.addMethod(MethodSpec.constructorBuilder()
          .addModifiers(Modifier.PUBLIC)
          .addParameter(javax.sql.DataSource.class, "dataSource")
          .addStatement("this.dataSource = dataSource")
          .addStatement("this.mapper = new DefaultEntityMapper()")
          .build());
    }
    fb.addMethod(createMeth);
    return fb.build();
  }

  // =========================================================================
  // DefaultEntityMapper (private inner class, convention case)
  //
  // - columns()       → literal list fixed at compile time
  // - toEntity(row)   → VarHandle.set() from Map values — no setter needed
  // - toFieldValues() → VarHandle.get() into FieldValue list — no getter needed
  // =========================================================================

  private TypeSpec buildDefaultMapper(ClassName entityCls,
                                      ParameterizedTypeName mapperType,
                                      EntityMetadata meta) {
    List<FieldInfo> fields = meta.getFields();

    TypeSpec.Builder tb = TypeSpec.classBuilder("DefaultEntityMapper")
        .addModifiers(Modifier.PRIVATE, Modifier.FINAL)
        .addSuperinterface(mapperType);

    // One static VarHandle per entity field
    for (FieldInfo f : fields) {
      tb.addField(FieldSpec.builder(
              java.lang.invoke.VarHandle.class,
              varHandleName(f.getFieldName()),
              Modifier.PRIVATE, Modifier.STATIC, Modifier.FINAL)
          .build());
    }

    tb.addStaticBlock(buildVarHandleStaticInit(entityCls, fields));
    tb.addMethod(buildDefaultColumns(fields));
    tb.addMethod(buildDefaultToEntity(entityCls, fields));
    tb.addMethod(buildDefaultToFieldValues(entityCls, fields));

    return tb.build();
  }

  private CodeBlock buildVarHandleStaticInit(ClassName entityCls, List<FieldInfo> fields) {
    CodeBlock.Builder cb = CodeBlock.builder()
        .beginControlFlow("try")
        .addStatement(
          "$T lk = $T.privateLookupIn($T.class, $T.lookup())",
          java.lang.invoke.MethodHandles.Lookup.class,
          java.lang.invoke.MethodHandles.class,
          entityCls,
          java.lang.invoke.MethodHandles.class);

    for (FieldInfo f : fields) {
      cb.addStatement("$L = lk.findVarHandle($T.class, $S, $T.class)",
          varHandleName(f.getFieldName()),
          entityCls,
          f.getFieldName(),
          ClassName.bestGuess(f.getFieldFqn()));
    }

    cb.nextControlFlow("catch ($T e)", ReflectiveOperationException.class)
      .addStatement("throw new $T(e)", ExceptionInInitializerError.class)
      .endControlFlow();

    return cb.build();
  }

  private MethodSpec buildDefaultColumns(List<FieldInfo> fields) {
    StringBuilder sb = new StringBuilder("return $T.of(\n");
    List<Object> args = new ArrayList<>();
    args.add(List.class);
    for (int i = 0; i < fields.size(); i++) {
      FieldInfo f = fields.get(i);
      sb.append(f.isId() ? "    $T.id($S, $S)" : "    $T.of($S, $S)");
      args.add(ColumnDescriptor.class);
      args.add(f.getFieldName());
      args.add(f.getFieldName());
      if (i < fields.size() - 1) sb.append(",\n");
    }
    sb.append("\n)");
    return MethodSpec.methodBuilder("columns")
        .addModifiers(Modifier.PUBLIC).addAnnotation(Override.class)
        .returns(ParameterizedTypeName.get(
            ClassName.get(List.class), ClassName.get(ColumnDescriptor.class)))
        .addStatement(sb.toString(), args.toArray())
        .build();
  }

  /**
   * Generates {@code toEntity(Map<String, Object> row)} using VarHandle
   * for direct field writes — no setter required on the entity.
   *
   * <pre>{@code
   * User entity = new User();
   * VH_ID      .set(entity, row.get("id"));
   * VH_USERNAME.set(entity, row.get("username"));
   * return entity;
   * }</pre>
   */
  private MethodSpec buildDefaultToEntity(ClassName entityCls, List<FieldInfo> fields) {
    ParameterizedTypeName rowType = ParameterizedTypeName.get(
        ClassName.get(Map.class), ClassName.get(String.class), ClassName.get(Object.class));

    MethodSpec.Builder b = MethodSpec.methodBuilder("toEntity")
        .addModifiers(Modifier.PUBLIC).addAnnotation(Override.class)
        .returns(entityCls)
        .addParameter(rowType, "row")
        .addStatement("$T entity = new $T()", entityCls, entityCls);

    for (FieldInfo f : fields) {
      // Convention: fieldName == columnName
      b.addStatement("$L.set(entity, row.get($S))",
          varHandleName(f.getFieldName()), f.getFieldName());
    }
    b.addStatement("return entity");
    return b.build();
  }

  /**
   * Generates {@code toFieldValues(T entity)} using VarHandle for direct
   * field reads — no getter required on the entity.
   *
   * <pre>{@code
   * List<ColumnDescriptor> cols = columns();
   * return List.of(
   *     FieldValue.of(cols.get(0), VH_ID.get(entity)),
   *     FieldValue.of(cols.get(1), VH_USERNAME.get(entity)),
   *     ...
   * );
   * }</pre>
   */
  private MethodSpec buildDefaultToFieldValues(ClassName entityCls, List<FieldInfo> fields) {
    ParameterizedTypeName listFv = ParameterizedTypeName.get(
        ClassName.get(List.class), ClassName.get(FieldValue.class));

    MethodSpec.Builder b = MethodSpec.methodBuilder("toFieldValues")
        .addModifiers(Modifier.PUBLIC).addAnnotation(Override.class)
        .returns(listFv)
        .addParameter(entityCls, "entity")
        .addStatement("$T<$T> cols = columns()", List.class, ColumnDescriptor.class);

    // Build the return statement as List.of(FieldValue.of(cols.get(i), VH_X.get(entity)), ...)
    StringBuilder sb = new StringBuilder("return $T.of(\n");
    List<Object> args = new ArrayList<>();
    args.add(List.class);
    for (int i = 0; i < fields.size(); i++) {
      FieldInfo f = fields.get(i);
      sb.append("    $T.of(cols.get($L), $L.get(entity))");
      args.add(FieldValue.class);
      args.add(i);
      args.add(varHandleName(f.getFieldName()));
      if (i < fields.size() - 1) sb.append(",\n");
    }
    sb.append("\n)");
    b.addStatement(sb.toString(), args.toArray());
    return b.build();
  }

